export const defaultThemeName = "blue";

const STORAGE_KEY = "portfolio-accent-theme";

export function getSavedThemeName(): string {
  if (typeof window === "undefined") return defaultThemeName;
  try {
    return localStorage.getItem(STORAGE_KEY) || defaultThemeName;
  } catch {
    return defaultThemeName;
  }
}

export function saveThemeName(name: string): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY, name);
  } catch {
    /* noop */
  }
}

export function findTheme(name: string): AccentTheme {
  return accentThemes.find((t) => t.name === name) ?? accentThemes[0];
}

export function applyThemeToDocument(theme: AccentTheme): void {
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  for (const [shade, value] of Object.entries(theme.colors)) {
    root.style.setProperty(`--primary-${shade}`, value);
  }
  for (const [shade, value] of Object.entries(theme.rgb)) {
    root.style.setProperty(`--primary-${shade}-rgb`, value);
  }
}
